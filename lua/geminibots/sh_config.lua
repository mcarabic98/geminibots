--[[
    GeminiBots - Configuration File
    Все основные параметры ботов вынесены сюда для легкой настройки без правки кода логики.
]]--

GeminiBots = GeminiBots or {}
GeminiBots.Config = {}

local CFG = GeminiBots.Config

--------------------------------------------------------------------------------
-- 1. Основные настройки (General)
--------------------------------------------------------------------------------
-- Включен ли ИИ ботов
CFG.Enabled = true

-- Включены ли уникальные имена для ботов (из data/geminibots/names.txt)
CFG.CustomNames = true

-- Сохранять и восстанавливать ботов при смене карты / перезагрузке
CFG.PreserveBots = true

-- Режим отладки: визуализация путей, конуса зрения и вывод сообщений в консоль
CFG.Debug = false
CFG.DebugDraw = false       -- Рисовать линии взгляда и путевые точки

-- Случайная внешность ботов при спавне
CFG.Appearance = {
    Enabled = true,         -- Включить случайную внешность
    RandomModel = true,     -- Случайная модель из всех валидных
    RandomSkin = true,      -- Случайный скин модели (0 .. SkinCount-1)
    RandomBodygroups = true,-- Случайные бодигруппы модели
    RandomColor = true,     -- Случайный цвет игрока (SetPlayerColor)
    -- Менять ли внешность при КАЖДОМ возрождении (true) или задать один раз
    -- при первом спавне и дальше не трогать (false)
    ChangeOnRespawn = true,
}

--------------------------------------------------------------------------------
-- 2. Экипировка и оружие (Loadout & Weapons)
--------------------------------------------------------------------------------
CFG.Loadout = {
    -- Выдавать ли случайное оружие при спавне
    Enabled = true,

    -- Диапазон количества выдаваемого оружия (от Min до Max)
    MinWeapons = 1,
    MaxWeapons = 3,

    -- Очищать ли дефолтное оружие перед выдачей случайного набора
    StripDefaultWeapons = true,

    -- Количество запасных патронов, выдаваемых для каждого типа оружия
    AmmoAmount = 180,

    -- Умный подбор: не более одной гранаты/тактики/рукопашки и хотя бы
    -- один стреляющий ствол (иначе бот мог родиться с двумя гранатами)
    SmartLoadout = true,

    -- Базы SWEP не для ботов (точное совпадение класса).
    -- Обычные пушки паков сюда не пишем, их режет фильтр спавна.
    IncompatibleBases = {
        ["weapon_swcs_base"] = true
    },

    -- Пул оружия: сюда можно добавлять любые классы (дефолтные HL2, M9K, TFA, ArcCW, CW2.0 и т.д.)
    -- Если оружие из стороннего аддона не установлено на сервере, бот просто пропустит его без ошибок.
    WeaponPool = {
        -- Стандартное оружие Garry's Mod / HL2
        "weapon_pistol",
        "weapon_357",
        "weapon_smg1",
        "weapon_ar2",
        "weapon_shotgun",
        "weapon_crossbow",

        -- Популярный пак M9K Specialties / Small Arms / Assault Rifles (будет браться, если установлен)
        "m9k_colt1911",
        "m9k_deagle",
        "m9k_glock",
        "m9k_ak47",
        "m9k_m4a1",
        "m9k_mp5",
        "m9k_spas12",
        "m9k_remington870",
        "m9k_awp",
        "m9k_barret_m82"
    }
}

--------------------------------------------------------------------------------
-- 3. Чат и реакции ботов (Chat & Personality)
--------------------------------------------------------------------------------
CFG.Chat = {
    -- Включены ли сообщения ботов в текстовый чат
    Enabled = true,

    -- Вероятность (от 0.0 до 1.0), что бот напишет сообщение после того, как убил кого-то (40%)
    KillChance = 0.40,

    -- Вероятность (от 0.0 до 1.0), что бот напишет сообщение после собственной смерти (35%)
    DeathChance = 0.35,

    -- Вероятность ответа жертвы-бота на обвинение убийцы-бота (мини-диалог, 50%)
    ComebackChance = 0.50,

    -- Имитация времени набора сообщения (задержка перед отправкой в чат, секунды)
    MinTypingDelay = 0.6,
    MaxTypingDelay = 1.8,

    -- Фразы, когда бот УБИЛ кого-то.
    -- Доступен плейсхолдер {victim} — имя жертвы.
    KillMessages = {
        "легко, {victim}",
        "потренируйся еще, {victim}",
        "ez",
        "минус один",
        "отдохни в спектрах, {victim}",
        "кто следующий?",
        "не повезло тебе, {victim}",
        "gg wp",
        "дефолтный фраг",
        "на прицел не попадайся больше"
    },

    -- Фразы, когда бота УБИЛИ.
    -- Доступен плейсхолдер {killer} — имя убийцы.
    DeathMessages = {
        "как так-то...",
        "лакер {killer}",
        "у меня пинг 300 был",
        "рандомная тычка",
        "ну погоди, {killer}",
        "читер что ли?",
        "ладно, 1:1 скоро будет",
        "пули сквозь стены летят?",
        "сейчас вернусь, {killer}",
        "ай..."
    }
}

--------------------------------------------------------------------------------
-- 4. Сенсорика и зрение (Perception & Vision)
--------------------------------------------------------------------------------
-- Угол поля зрения бота в градусах (например, 110 = 55 градусов влево и вправо)
CFG.VisionFOV = 110

-- Максимальная дистанция обнаружения врагов в единицах Source (юнитах)
CFG.VisionRange = 2500

-- Дистанция, на которой бот слышит шаги/бег (юниты)
CFG.HearingRange = 700

-- Дистанция, на которой бот слышит выстрелы оружия сквозь стены/по коридорам (юниты)
CFG.GunHearingRange = 3000

-- Сколько секунд бот помнит врага после потери прямой видимости
CFG.MemoryDuration = 6.0

-- Интервал сканирования целей (секунды)
CFG.ScanInterval = 0.2

-- Режим целей: кого боту разрешено атаковать
-- "both"    — всех подряд, ближайший побеждает (по умолчанию);
-- "pve"     — NPC в приоритете, игроки — только если NPC рядом нет;
-- "players" — только игроки (NPC игнорируются даже в ответ);
-- "npcs"    — только NPC (ботов и игроков не трогает).
CFG.Targeting = {
    Mode = "both"
}

--------------------------------------------------------------------------------
-- 5. Прицеливание и реакция (Aim & Accuracy)
--------------------------------------------------------------------------------
-- Задержка перед началом стрельбы после первого обнаружения цели (секунды)
CFG.ReactionTimeMin = 0.15
CFG.ReactionTimeMax = 0.35

-- Скорость доводки прицела (градусов в секунду). Выше = быстрее целится.
CFG.AimSpeed = 360

-- Плавность наведения (фактор LerpAngle, от 0.1 до 1.0)
CFG.AimSmoothing = 0.25

-- Предугадывание движения цели (упреждение с учетом скорости и дистанции)
CFG.AimPrediction = true

-- Разброс прицела бота в градусах (чем выше, тем чаще промахивается)
CFG.AimSpread = 1.8

-- Шанс целиться в голову вместо центра туловища (от 0.0 до 1.0)
CFG.HeadshotChance = 0.35

--------------------------------------------------------------------------------
-- 6. Боевое поведение (Combat Behavior)
--------------------------------------------------------------------------------
-- Дистанция удержания боя (стремится оставаться в этом диапазоне)
CFG.CombatMinDistance = 250
CFG.CombatMaxDistance = 900

-- Вероятность приседать во время стрельбы (0.0 - 1.0)
CFG.CrouchChance = 0.25

-- Частота смены направления стрейфа во время перестрелки (секунды)
CFG.StrafeIntervalMin = 0.8
CFG.StrafeIntervalMax = 2.0

-- Порог здоровья (в процентах от макс. HP), ниже которого бот может перейти в отступление (flee)
CFG.FleeHealthThreshold = 0.25

-- Прострел укрытий: короткая очередь сквозь стекло/хрупкое по свежему следу
CFG.WallbangEnabled = true

-- C4 от SWCS: подрывник ставит, остальные ищут и разминируют
CFG.C4Enabled = true

-- Реакции на тактику SWCS. Без самого SWCS не работают.
CFG.SWCS = {
    -- Шанс пойти проверять звук декоя (не на каждый звук)
    DecoyChance = 0.40,
    -- Отходить от огня молика/зажигательной вместо ходьбы сквозь него
    FireAvoid = true,
    -- Дистанция реакции на swcs_inferno (юниты)
    FireRadius = 320,
}

--------------------------------------------------------------------------------
-- 7. Навигация и движение (Navigation & Movement)
--------------------------------------------------------------------------------
-- Радиус достижения путевой точки (юниты)
CFG.WaypointReachRadius = 45

-- Высота уступа, требующая прыжка
CFG.JumpObstacleHeight = 18

-- Время застревания (секунды)
CFG.StuckTimeout = 1.5

-- Дистанция взаимодействия с дверями/кнопками (нажатие кнопки USE)
CFG.DoorInteractionRange = 65

-- Баннихоп: прыжки на ходу. Шанс ниже 1.0 выглядит живее.
CFG.BunnyHop = {
    Enabled = true,   -- Прыгать при касании земли на ходу
    Chance = 0.85,    -- Шанс прыжка на каждое приземление (0.0 - 1.0)
}
